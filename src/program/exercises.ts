/**
 * Exercise catalogue. Every exercise the program can ever log — primaries from
 * the block tables, the document's "X or Y" alternatives, the Part 7 core
 * drills, and every substitute named in the Part 3 table — so that a
 * substitute logs against its own history.
 *
 * `substitutes` is the Part 3 list for the exercise's pattern, in the
 * document's order, minus the exercise itself. Where Part 3 says "the other
 * curl machine" the list is written per exercise.
 */

