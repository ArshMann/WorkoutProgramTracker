export type ExerciseId = keyof typeof EXERCISES;

export function getExercise(id: string): ExerciseDef {
  const def = (EXERCISES as Catalogue)[id];
  if (!def) throw new Error(`Unknown exercise id: ${id}`);
  return def;
}

export function isExerciseId(id: string): id is ExerciseId {
  return Object.prototype.hasOwnProperty.call(EXERCISES, id);
}

/**
 * Part 1.5: the calibration nudge is only ever offered on machine/cable
 * isolation work — never on squat, bench, deadlift, OHP or any barbell lift.
 */
export function isCalibrationEligible(id: string): boolean {
  const def = getExercise(id);
  return def.equipment === 'machine-cable' && def.role === 'isolation';
}
